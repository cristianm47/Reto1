package reto1;

public class Funciones2 {
	public static int restar(int a, int b) {
		return a - b;
	}
	public static int sumar(int a, int b) {
		return a + b;
	}
	public static boolean esPar(int a) {
		if (a%2==0) {
			return true;
		}
		else {
		return false;
		}
	}
	public static boolean esimPar(int a) {
		if (a%2!=0) {
			return true;
		}
		else {
		return false;
		}
	}
}
